    fun getDhikrById(id: Int): Dhikr? = allDhikrs.find { it.id == id }

    fun getDhikrsByCategory(categoryId: String): List<Dhikr> =
        allDhikrs.filter { it.categoryId == categoryId }

    fun searchDhikrs(query: String): List<Dhikr> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return allDhikrs
        return allDhikrs.filter {
            it.title.lowercase().contains(trimmed) ||
            it.text.lowercase().contains(trimmed) ||
            it.source.lowercase().contains(trimmed) ||
            it.benefit.lowercase().contains(trimmed)
        }
    }
